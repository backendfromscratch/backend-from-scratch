// The shop's tables, described in TypeScript for Drizzle. The migrations create them
// (db/migrations/); this file tells Drizzle what they're like, so it can write the queries and know
// what type each column has. Each column carries its name in the database (price_cents) and the
// property's name in TypeScript (priceCents): Drizzle translates from one to the other.
// The migrations table isn't here: it belongs to our runner (scripts/migrate.ts), not to the shop.
import { relations, sql } from 'drizzle-orm';
import { check, index, integer, pgTable, primaryKey, text, timestamp } from 'drizzle-orm/pg-core';
import type { OrderStatus } from './data.ts';

// #region products
export const products = pgTable(
  'products',
  {
    id: integer().primaryKey().generatedAlwaysAsIdentity(),
    name: text().notNull(),
    priceCents: integer('price_cents').notNull(),
    stock: integer().notNull().default(0),
  },
  (table) => [
    check('products_price_cents_check', sql`${table.priceCents} > 0`),
    check('stock_not_negative', sql`${table.stock} >= 0`),
  ],
);
// #endregion products

export const categories = pgTable('categories', {
  id: integer().primaryKey().generatedAlwaysAsIdentity(),
  name: text().notNull().unique(),
});

// #region product-categories
export const productCategories = pgTable(
  'product_categories',
  {
    productId: integer('product_id')
      .notNull()
      .references(() => products.id, { onDelete: 'cascade' }),
    categoryId: integer('category_id')
      .notNull()
      .references(() => categories.id, { onDelete: 'cascade' }),
  },
  (table) => [
    primaryKey({ columns: [table.productId, table.categoryId] }),
    // The primary key (product_id, category_id) already works for searching by product, because
    // it starts with that column. To search by category (the ?category= filter) another index that
    // starts with category_id is needed. Migration 004, generated by drizzle-kit, adds it.
    index('product_categories_by_category').on(table.categoryId),
  ],
);
// #endregion product-categories

// #region orders
// $type tells TypeScript which texts status can have: the four in OrderStatus.
export const orders = pgTable(
  'orders',
  {
    id: integer().primaryKey().generatedAlwaysAsIdentity(),
    productId: integer('product_id')
      .notNull()
      .references(() => products.id),
    quantity: integer().notNull(),
    status: text().$type<OrderStatus>().notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull(),
  },
  (table) => [
    check('orders_quantity_check', sql`${table.quantity} > 0`),
    check(
      'orders_status_check',
      sql`${table.status} IN ('pending', 'paid', 'shipped', 'cancelled')`,
    ),
    index('orders_by_date').on(table.createdAt.desc(), table.id.desc()),
  ],
);
// #endregion orders

export const idempotencyKeys = pgTable('idempotency_keys', {
  key: text().primaryKey(),
  requestBody: text('request_body').notNull(),
  status: integer().notNull(),
  body: text().notNull(),
  location: text(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
});

export const processedEvents = pgTable('processed_events', {
  id: text().primaryKey(),
  processedAt: timestamp('processed_at', { withTimezone: true }).notNull().defaultNow(),
});

// #region relations
// Relations don't change anything in the database: they tell Drizzle how the tables are joined,
// so it can ask for "the products with their categories" at once (with, in data.ts).
export const productsRelations = relations(products, ({ many }) => ({
  categories: many(productCategories),
}));

export const productCategoriesRelations = relations(productCategories, ({ one }) => ({
  product: one(products, {
    fields: [productCategories.productId],
    references: [products.id],
  }),
  category: one(categories, {
    fields: [productCategories.categoryId],
    references: [categories.id],
  }),
}));
// #endregion relations
